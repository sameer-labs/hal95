/**
 * Generate the public draw samples from the deployed Worker.
 *
 *   node tools/make-draw-samples.mjs
 *
 * The Worker holds the DeepSeek key, so this script needs no secret. It obeys
 * the /draw rate limit (5 per minute per IP) by waiting for Retry-After, saves
 * the sanitized SVG responses, then renders each one to a PNG with Chromium.
 *
 * Output: docs/draw-samples/*.svg, docs/draw-samples/*.png, captions.md
 */

import { chromium } from "playwright";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const WORKER = process.env.HAL95_WORKER ?? "https://hal95-worker.sameer0ayat.workers.dev";
const OUT = "docs/draw-samples";

const SUBJECTS = [
  ["horse", "a horse"],
  ["cat", "a cat"],
  ["rocket", "a rocket"],
  ["mum", "my mum"],
  ["meaning-of-life", "the meaning of life"],
  ["dog", "a dog"],
  ["house", "a lonely house at night"],
  ["moon", "the moon"],
  ["sandwich", "a sandwich"],
  ["bicycle", "a bicycle"],
];

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function draw(prompt) {
  for (let attempt = 0; attempt < 8; attempt += 1) {
    const response = await fetch(`${WORKER}/draw`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Origin: "https://sameer-labs.github.io",
      },
      body: JSON.stringify({ prompt }),
    });

    if (response.status === 429) {
      const retry = Number(response.headers.get("Retry-After")) || 60;
      console.log(`rate limited, waiting ${retry}s`);
      await sleep((retry + 2) * 1_000);
      continue;
    }

    const data = await response.json().catch(() => ({}));
    if (!response.ok || typeof data.svg !== "string") {
      throw new Error(`draw failed for "${prompt}": ${response.status} ${data.error ?? ""}`);
    }
    return data;
  }

  throw new Error(`gave up waiting for the draw limit: "${prompt}"`);
}

async function render(browser, file) {
  const svg = await readFile(file);
  const page = await browser.newPage({ viewport: { width: 640, height: 480 } });
  const dataUrl = `data:image/svg+xml;base64,${svg.toString("base64")}`;
  await page.setContent(
    `<!doctype html><style>html,body{margin:0;background:#fff}img{display:block;width:640px;height:480px;image-rendering:pixelated}</style><img id="art" alt="" src="${dataUrl}">`,
  );
  await page.waitForFunction(() => {
    const image = document.querySelector("#art");
    return image.complete && image.naturalWidth > 0;
  });
  await page.locator("#art").screenshot({ path: file.replace(/\.svg$/, ".png") });
  await page.close();
}

await mkdir(OUT, { recursive: true });

const captions = [];
for (const [slug, prompt] of SUBJECTS) {
  const drawing = await draw(prompt);
  const file = join(OUT, `${slug}.svg`);
  await writeFile(file, drawing.svg, "utf8");
  captions.push(`- **${slug}** — "${prompt}" → ${drawing.caption}`);
  console.log(`saved ${file} (${drawing.svg.length} bytes) — ${drawing.caption}`);
}

await writeFile(
  join(OUT, "captions.md"),
  `# HAL95 draw samples\n\nGenerated by the deployed Worker using DeepSeek, sanitized server-side, then rendered headlessly to PNG.\n\n${captions.join("\n")}\n`,
  "utf8",
);

const browser = await chromium.launch();
try {
  for (const [slug] of SUBJECTS) {
    await render(browser, join(OUT, `${slug}.svg`));
    console.log(`rendered ${slug}.png`);
  }
} finally {
  await browser.close();
}

console.log(`\n${SUBJECTS.length} drawings generated and rendered in ${OUT}`);
